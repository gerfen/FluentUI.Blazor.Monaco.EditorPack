import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const r = await build({
  entryPoints: ['src/index.js'], bundle: true, format: 'esm', write: false, metafile: true,
  outdir: 'out', target: 'es2020', logLevel: 'silent'
});
const pkgs = new Map();
for (const input of Object.keys(r.metafile.inputs)) {
  const i = input.replace(/\\/g, '/').lastIndexOf('node_modules/');
  if (i < 0) continue;
  const rest = input.replace(/\\/g, '/').slice(i + 'node_modules/'.length).split('/');
  const name = rest[0].startsWith('@') ? rest[0] + '/' + rest[1] : rest[0];
  const root = input.replace(/\\/g, '/').slice(0, i) + 'node_modules/' + name;
  pkgs.set(name, root);
}
let out = `THIRD-PARTY NOTICES\n\nFluentUI.Blazor.Monaco.EditorPack.Wysiwyg bundles the following open-source packages\n(wwwroot/js/milkdown-editor.js and milkdown-editor.css). Generated by Js/generate-notices.mjs.\n\n`;
out += `Note: dompurify is dual-licensed (MPL-2.0 OR Apache-2.0); it is used here under the Apache-2.0 license.\n\n`;
for (const [name, root] of [...pkgs].sort((a, b) => a[0].localeCompare(b[0]))) {
  const pj = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const lic = typeof pj.license === 'string' ? pj.license : JSON.stringify(pj.license);
  const file = fs.readdirSync(root).find(f => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  out += `${'='.repeat(72)}\n${name}@${pj.version}  (${lic})\n${pj.homepage || (pj.repository?.url ?? '')}\n${'-'.repeat(72)}\n`;
  out += file ? fs.readFileSync(path.join(root, file), 'utf8').trim() + '\n\n' : `(no license file shipped in package; declared license: ${lic})\n\n`;
}
fs.writeFileSync('../THIRD-PARTY-NOTICES.txt', out);
const nolic = [...pkgs.keys()].filter(n => !fs.readdirSync(pkgs.get(n)).some(f => /^(licen[sc]e|copying)/i.test(f)));
console.log('bundled packages:', pkgs.size, '| without license file:', nolic.join(', ') || 'none');
